"""
export_database.py
==================
Exports processed Parquet splits to CSV format for faculty submission.
Writes data/processed/train.csv, val.csv, test.csv, and data/processed/database_readme.txt.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
import pandas as pd

PROJECT_ROOT = Path(__file__).parent.resolve()
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"


def main():
    splits = ["train", "val", "test"]
    present_parquets = {}

    for s in splits:
        p_path = DATA_PROCESSED_DIR / f"{s}.parquet"
        if not p_path.exists():
            # Fallback to _phase2 naming if present
            alt_path = DATA_PROCESSED_DIR / f"{s}_phase2.parquet"
            if alt_path.exists():
                p_path = alt_path

        if p_path.exists():
            present_parquets[s] = p_path
        else:
            print(f"[MISSING] {DATA_PROCESSED_DIR / f'{s}.parquet'}")

    if not present_parquets:
        print("Parquet files not found — run Phase 1-2 first with CIC_DATA_RAW_DIR set")
        sys.exit(0)

    # Load selected features to ensure exactly 19 features + label_8class
    feat_path = PROJECT_ROOT / "artifacts" / "selected_features.json"
    if feat_path.exists():
        with open(feat_path, "r", encoding="utf-8") as f:
            features = json.load(f)
        if isinstance(features, dict) and "selected_features" in features:
            features = features["selected_features"]
    else:
        features = None

    row_counts = {}

    for s, p_path in present_parquets.items():
        print(f"Reading {p_path.name} ...")
        df = pd.read_parquet(p_path)

        # Select 19 features + 8-class label
        if features is not None:
            lbl_col = "label_8class" if "label_8class" in df.columns else "label_8"
            export_cols = [c for c in features if c in df.columns]
            if lbl_col in df.columns:
                export_cols.append(lbl_col)
            df_export = df[export_cols].copy()
            if lbl_col in df_export.columns and lbl_col != "label_8class":
                df_export = df_export.rename(columns={lbl_col: "label_8class"})
        else:
            df_export = df.copy()

        csv_path = DATA_PROCESSED_DIR / f"{s}.csv"
        print(f"Writing {csv_path.name} ({len(df_export)} rows, {len(df_export.columns)} cols) ...")
        df_export.to_csv(csv_path, index=False)

        row_counts[s] = len(df_export)
        print(f"  [OK] {s}.csv: {len(df_export)} rows, {len(df_export.columns)} columns")

    # Write database_readme.txt
    n_train = row_counts.get("train", "N/A")
    n_val = row_counts.get("val", "N/A")
    n_test = row_counts.get("test", "N/A")

    readme_content = (
        "CICIoT2023 processed splits\n"
        f"train.csv  : {n_train} rows, 20 columns (19 features + label_8class)\n"
        f"val.csv    : {n_val} rows, 20 columns\n"
        f"test.csv   : {n_test} rows, 20 columns\n"
        "Features   : see artifacts/selected_features.json\n"
        "Labels     : 8-class (Benign, DDoS, DoS, Recon, Web-based,\n"
        "             BruteForce, Spoofing, Mirai)\n"
        "Generated by export_database.py from Phase 1-2 Parquet outputs\n"
    )

    readme_path = DATA_PROCESSED_DIR / "database_readme.txt"
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(readme_content)

    print(f"\n[OK] Metadata written to {readme_path.name}")
    print("\nDatabase Readme Preview:")
    print("----------------------------------------------------------------------")
    print(readme_content.strip())
    print("----------------------------------------------------------------------")


if __name__ == "__main__":
    main()
